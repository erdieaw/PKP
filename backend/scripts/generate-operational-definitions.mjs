import assert from 'node:assert/strict';
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';

// Generates an immutable data migration, never connects to a database or seeds history.
const root = new URL('../../docs/pkp-2026/', import.meta.url);
const source = JSON.parse(await readFile(new URL('../src/analytics/do2026/source.json', import.meta.url), 'utf8'));
const records = [];
for (const file of (await readdir(root)).filter(file => /-bagian-\d+\.md$/.test(file)).sort()) {
  const markdown = await readFile(new URL(file, root), 'utf8');
  for (const match of markdown.matchAll(/```json\n([\s\S]*?)\n```/g)) records.push(JSON.parse(match[1]));
}
assert.equal(records.length, 272);
assert.equal(new Set(records.map(row => row.catalogue_candidate)).size, 272);
const hash = 'c4baf039eb460c7ffe030b419973b78ce0739e6f92778fbb41f85f5d3ea22149';
const quote = value => value === null ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`;
const tuples = records.map(row => {
  const runtime = source.find(item => item.definitionId === row.id);
  assert.ok(runtime, row.id);
  assert.deepEqual(runtime, {
    indicatorId: row.catalogue_candidate, definitionId: row.id,
    sourceRef: `S1:${row.source.sheet}!${row.source.range}`,
    definition: row.definisi_operasional_raw, calculation: row.cara_penghitungan_raw,
    notes: row.keterangan_raw, target: row.target, formulaFamily: row.review.formula_family,
  });
  assert.ok(row.sumber_data_raw === null || typeof row.sumber_data_raw === 'string');
  const raw = row.target.raw;
  const target = typeof raw === 'number' && row.target.excel_number_format.includes('%') ? `${raw * 100}%` : String(raw ?? 'Belum ditetapkan');
  return `(${[row.id, 'DO_2026_V2', row.catalogue_candidate, row.definisi_operasional_raw, row.cara_penghitungan_raw, row.sumber_data_raw, row.keterangan_raw, target, runtime.sourceRef, hash, 'Indikator DO dan Target PKP 2026.xlsx', JSON.stringify(row)].map(quote).join(', ')}, 2026)`;
});
const sql = `-- Generated by scripts/generate-operational-definitions.mjs from the 272 MD records.
-- No historical records, targets, catalogue identities or scoring versions are changed.
BEGIN;
CREATE TABLE "operational_definitions" (
  "definitionId" TEXT NOT NULL,
  "version" TEXT NOT NULL,
  "indicatorId" TEXT NOT NULL,
  "definition" TEXT NOT NULL,
  "calculation" TEXT NOT NULL,
  "dataSource" TEXT,
  "notes" TEXT,
  "targetDisplay" TEXT NOT NULL,
  "sourceRef" TEXT NOT NULL,
  "sourceHash" TEXT NOT NULL CHECK ("sourceHash" ~ '^[a-f0-9]{64}$'),
  "sourceFile" TEXT NOT NULL,
  "sourceRecord" JSONB NOT NULL,
  "year" INTEGER NOT NULL CHECK ("year" BETWEEN 2000 AND 2100),
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "operational_definitions_pkey" PRIMARY KEY ("definitionId", "version")
);
CREATE UNIQUE INDEX "operational_definitions_indicatorId_version_key" ON "operational_definitions"("indicatorId", "version");
CREATE INDEX "operational_definitions_year_indicatorId_idx" ON "operational_definitions"("year", "indicatorId");
INSERT INTO "operational_definitions" ("definitionId", "version", "indicatorId", "definition", "calculation", "dataSource", "notes", "targetDisplay", "sourceRef", "sourceHash", "sourceFile", "sourceRecord", "year") VALUES
${tuples.join(',\n')};
CREATE FUNCTION preserve_operational_definition() RETURNS trigger LANGUAGE plpgsql AS $function$
BEGIN
  RAISE EXCEPTION 'Operational definitions are immutable; insert a new version instead' USING ERRCODE = '23514';
END;
$function$;
CREATE TRIGGER operational_definitions_immutable BEFORE UPDATE OR DELETE ON "operational_definitions"
FOR EACH ROW EXECUTE FUNCTION preserve_operational_definition();
COMMIT;
`;
const directory = new URL('../prisma/migrations/20261028173000_operational_definitions/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL('migration.sql', directory), sql);
console.log(`Generated immutable migration for ${records.length} definitions; source parity verified.`);
